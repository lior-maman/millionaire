ACTIVITIES = [
    {"name": "General Knowledge", "questions": EASY + MEDIUM + HARD},
    {"name": "Sports & Entertainment", "questions": SPORT_EASY + SPORT_MEDIUM + SPORT_HARD},
]


async def seed_data() -> None:
    """Upsert all activities. Assumes Mongo is already connected."""
    coll = activities_collection()
    for activity in ACTIVITIES:
        result = await coll.replace_one(
            {"name": activity["name"]}, activity, upsert=True
        )
        doc = await coll.find_one({"name": activity["name"]}, {"_id": 1})
        print(
            f"Seeded '{activity['name']}' with {len(activity['questions'])} questions "
            f"-> id: {doc['_id']} "
            f"(matched={result.matched_count}, upserted={result.upserted_id is not None})"
        )


async def seed_if_empty() -> None:
    """Seed only when there are no activities yet. Called on startup in Docker."""
    coll = activities_collection()
    if await coll.count_documents({}) == 0:
        print("No activities found — seeding initial data…")
        await seed_data()
    else:
        print("Activities already present — skipping seed.")


async def seed() -> None:
    """Standalone entry point: connect, seed, disconnect."""
    await connect_to_mongo()
    await seed_data()
    await close_mongo_connection()


if __name__ == "__main__":
    asyncio.run(seed())
